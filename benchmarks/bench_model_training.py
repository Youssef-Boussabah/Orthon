"""Unified synthetic model-training benchmark for Orthon.

Defaults are intentionally short and download-free. Accuracy is reported only
as synthetic train accuracy because labels are generated by this script.
"""

from benchmarks._support.training import measured, configure, options, run as run_measurement
from benchmarks._support.environment import synchronizer, cuda_available

import argparse

import orthon as ortho
from orthon.nn import Conv2d, Linear, MaxPool2d, Module, ReLU, Sequential
from orthon.optim import Adam, SGD


class SmallCNN(Module):
    def __init__(self, channels):
        super().__init__()
        self.channels = channels
        self.features = Sequential(
            Conv2d(3, channels, kernel_size=3, padding=1),
            ReLU(),
            MaxPool2d(kernel_size=2),
        )
        self.classifier = Linear(channels * 16 * 16, 10)

    def forward(self, x):
        out = self.features(x)
        out = ortho.reshape(out, [x.shape[0], self.channels * 16 * 16])
        return self.classifier(out)


def make_mlp(input_dim, hidden):
    return Sequential(Linear(input_dim, hidden), ReLU(), Linear(hidden, 10))


def init_params(model):
    for index, param in enumerate(model.parameters()):
        param.fill_(0.01 * (index + 1))


def make_synthetic_mlp_batch(batch_size, input_dim, device):
    import numpy as np

    values = np.zeros((batch_size, input_dim), dtype=np.float32)
    labels = []
    for row in range(batch_size):
        label = row % 10
        labels.append(label)
        values[row, label % input_dim] = 1.0
        values[row, (label + 10) % input_dim] = 0.5
    x = ortho.from_numpy(values)
    return (x.to(device) if device == "cuda" else x), labels


def make_synthetic_cnn_batch(batch_size, device):
    import numpy as np

    values = np.zeros((batch_size, 3, 32, 32), dtype=np.float32)
    labels = []
    for row in range(batch_size):
        label = row % 10
        labels.append(label)
        channel = label % 3
        pixel = 4 + label
        values[row, channel, pixel, pixel] = 1.0
        values[row, channel, pixel + 1, pixel] = 0.5
    x = ortho.from_numpy(values)
    return (x.to(device) if device == "cuda" else x), labels


def accuracy(logits, targets):
    cpu_logits = logits.to("cpu") if logits.device.is_cuda() else logits
    values = cpu_logits.tolist()
    classes = int(logits.shape[1])
    correct = 0
    for row, target in enumerate(targets):
        start = row * classes
        pred = max(range(classes), key=lambda col: values[start + col])
        correct += int(pred == target)
    return correct / len(targets)


def sync(device):
    synchronizer(device, "orthon")()


def train_step(model, optimizer, x, targets):
    optimizer.zero_grad()
    logits = model(x)
    loss = ortho.cross_entropy(logits, targets)
    loss.backward()
    optimizer.step()
    return loss, logits


def evaluate_loss_accuracy(model, x, targets):
    logits = model(x)
    loss = ortho.cross_entropy(logits, targets)
    return float(loss.item()), accuracy(logits, targets)


def parse_args():
    parser = argparse.ArgumentParser(description="Orthon unified model-training benchmark.")
    parser.add_argument("--model", choices=["mlp", "cnn"], default="mlp")
    parser.add_argument("--dataset", choices=["synthetic"], default="synthetic")
    parser.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    parser.add_argument("--steps", type=int, default=10)
    parser.add_argument("--warmup", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--input-dim", type=int, default=32)
    parser.add_argument("--hidden", type=int, default=64)
    parser.add_argument("--channels", type=int, default=4)
    parser.add_argument("--optimizer", choices=["adam", "sgd"], default="adam")
    parser.add_argument("--lr", type=float, default=0.01)
    options(parser)
    args = configure(parser.parse_args())
    if args.steps < 1:
        parser.error("--steps must be at least 1")
    if args.warmup < 0:
        parser.error("--warmup must be >= 0")
    return args


def main():
    args = parse_args()
    if args.device == "cuda" and not cuda_available("cuda:0"):
        print("benchmark_name=model_training status=skipped reason=cuda_unavailable")
        return

    if args.model == "mlp":
        model = make_mlp(args.input_dim, args.hidden)
        x, targets = make_synthetic_mlp_batch(args.batch_size, args.input_dim, args.device)
        model_name = f"mlp_{args.input_dim}_{args.hidden}_10"
    else:
        model = SmallCNN(args.channels)
        x, targets = make_synthetic_cnn_batch(args.batch_size, args.device)
        model_name = f"cnn_channels_{args.channels}"
    init_params(model)
    model.to(args.device)

    if args.optimizer == "adam":
        optimizer = Adam(model.parameters(), lr=args.lr)
    else:
        optimizer = SGD(model.parameters(), lr=args.lr)

    initial_loss, initial_accuracy = evaluate_loss_accuracy(model, x, targets)

    for _ in range(args.warmup):
        train_step(model, optimizer, x, targets)
    sync(args.device)

    last_loss = None
    last_logits = None
    with measured("bench_model_training:start:main", lambda: sync(args.device), calls=args.steps, device=args.device, implementation="orthon", dtype="float32", config=vars(args)) as _region_start:
        for _ in range(args.steps):
            last_loss, last_logits = train_step(model, optimizer, x, targets)
        sync(args.device)
    elapsed = _region_start["seconds"]

    final_loss = float(last_loss.item())
    final_accuracy = accuracy(last_logits, targets)
    ms_per_step = elapsed * 1000.0 / args.steps
    samples_per_sec = args.batch_size * args.steps / elapsed

    print("benchmark_name: model_training")
    print(f"model: {model_name}")
    print(f"dataset: {args.dataset}")
    print(f"device: {args.device}")
    print(f"batch_size: {args.batch_size}")
    print(f"steps: {args.steps}")
    print(f"ms_per_step: {ms_per_step:.3f}")
    print(f"samples_per_sec: {samples_per_sec:.2f}")
    print(f"initial_loss: {initial_loss:.6f}")
    print(f"final_loss: {final_loss:.6f}")
    print(f"synthetic_train_accuracy_initial: {initial_accuracy:.4f}")
    print(f"synthetic_train_accuracy_final: {final_accuracy:.4f}")
    print("notes: synthetic fixed-batch training; accuracy is synthetic train accuracy only")
    print(
        "csv_summary,"
        "benchmark_name=model_training,"
        f"model={model_name},"
        f"dataset={args.dataset},"
        f"device={args.device},"
        f"batch_size={args.batch_size},"
        f"steps={args.steps},"
        f"ms_per_step={ms_per_step:.3f},"
        f"samples_per_sec={samples_per_sec:.2f},"
        f"initial_loss={initial_loss:.6f},"
        f"final_loss={final_loss:.6f},"
        f"synthetic_train_accuracy_initial={initial_accuracy:.4f},"
        f"synthetic_train_accuracy_final={final_accuracy:.4f}"
    )


if __name__ == "__main__":
    run_measurement(main, "bench_model_training")
